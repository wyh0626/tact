import AppKit
import ApplicationServices
import Carbon

/// How an accepted suggestion gets into the input box ("app.insert_method").
enum InsertMethod: String {
    /// Short single-line text is typed as key events, leaving the clipboard
    /// alone; everything else is pasted.
    case auto
    /// Always paste through the clipboard.
    case paste
    /// Set the accessibility value directly, falling back to paste. The host
    /// app may not notice a value it did not type itself.
    case ax
}

enum InsertAttempt: String {
    case type, paste, ax
}

enum InsertOutcome: Equatable {
    case inserted(InsertAttempt)
    /// The box changed, but not into the suggestion (partly typed, or the
    /// app rewrote it). Nothing more is tried, so text is never inserted twice.
    case mismatch
    /// Nothing landed in time. When the last attempt was a paste the
    /// suggestion is left on the clipboard rather than restoring the old
    /// content, because a paste that lands late would then insert that.
    case notApplied(leftOnClipboard: Bool)
}

enum VerifyState: Equatable {
    case done
    case unchanged
    case changedElsewhere
}

/// The clipboard as it was before a paste, to put back afterwards.
struct ClipboardSnapshot {
    let items: [[NSPasteboard.PasteboardType: Data]]
    /// Marked secret by a password manager (nspasteboard.org convention).
    let concealed: Bool
}

/// Writes the accepted suggestion into the input box and verifies the result
/// by reading the box back; posting key events is never taken as success on
/// its own. Never presses Return.
@MainActor
enum Inserter {
    /// Typing is for short replies: longer text takes visibly long to appear.
    nonisolated static let maxTypedUTF16 = 64

    // nspasteboard.org markers that clipboard history tools respect.
    nonisolated static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    nonisolated static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    nonisolated static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    static func insert(_ text: String, into element: AXUIElement, pid: pid_t, method: InsertMethod) async -> InsertOutcome {
        let before = AX.string(element, kAXValueAttribute) ?? ""
        for attempt in plan(text, method: method, inputMethodActive: inputMethodActive()) {
            let state: VerifyState
            switch attempt {
            case .paste:
                return await paste(text, into: element, before: before)
            case .type:
                state = await type(text, into: element, pid: pid, before: before)
            case .ax:
                state = await setValue(text, of: element, before: before)
            }
            switch state {
            case .done: return .inserted(attempt)
            case .changedElsewhere: return .mismatch
            case .unchanged: continue
            }
        }
        return .notApplied(leftOnClipboard: false)
    }

    /// Paste always comes last: it is the most reliable, and once it has run
    /// there is nothing left to fall back to.
    nonisolated static func plan(_ text: String, method: InsertMethod, inputMethodActive: Bool) -> [InsertAttempt] {
        switch method {
        case .paste: return [.paste]
        case .ax: return [.ax, .paste]
        case .auto: return canType(text, inputMethodActive: inputMethodActive) ? [.type, .paste] : [.paste]
        }
    }

    /// With an input method such as Pinyin active, synthetic key presses may
    /// be taken as composition keystrokes instead of text, so typing is only
    /// used under a plain keyboard layout.
    nonisolated static func canType(_ text: String, inputMethodActive: Bool) -> Bool {
        !inputMethodActive && !text.isEmpty && text.utf16.count <= maxTypedUTF16
            && !text.contains(where: \.isNewline)
    }

    nonisolated static func verify(observed: String, before: String, expected: String) -> VerifyState {
        if trimmed(observed) == trimmed(expected) { return .done }
        if observed == before { return .unchanged }
        return .changedElsewhere
    }

    nonisolated private static func trimmed(_ s: String) -> String {
        s.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    static func inputMethodActive() -> Bool {
        guard let source = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyInputSourceType) else { return true }
        let type = Unmanaged<CFString>.fromOpaque(raw).takeUnretainedValue()
        return !CFEqual(type, kTISTypeKeyboardLayout)
    }

    /// Polls the box until it holds the expected text or the budget runs out.
    /// Intermediate states (half-typed text) keep waiting.
    private static func waitForResult(_ element: AXUIElement, before: String, expected: String,
                                      budget: TimeInterval) async -> VerifyState {
        let deadline = Date().addingTimeInterval(budget)
        var state = VerifyState.unchanged
        repeat {
            state = verify(observed: AX.string(element, kAXValueAttribute) ?? "", before: before, expected: expected)
            if state == .done { return .done }
            try? await Task.sleep(nanoseconds: 15_000_000)
        } while Date() < deadline
        return state
    }

    // MARK: - Typing

    private static func type(_ text: String, into element: AXUIElement, pid: pid_t, before: String) async -> VerifyState {
        AX.select(element, location: 0, length: (before as NSString).length)
        // A private source keeps modifiers the user may still hold out of the events.
        let source = CGEventSource(stateID: .privateState)
        for character in text {
            let units = Array(String(character).utf16)
            guard let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false) else { break }
            for event in [down, up] {
                event.flags = []
                units.withUnsafeBufferPointer { event.keyboardSetUnicodeString(stringLength: $0.count, unicodeString: $0.baseAddress) }
                event.postToPid(pid)
            }
            try? await Task.sleep(nanoseconds: 1_000_000)
        }
        return await waitForResult(element, before: before, expected: text, budget: 0.3)
    }

    // MARK: - Accessibility value

    private static func setValue(_ text: String, of element: AXUIElement, before: String) async -> VerifyState {
        guard AX.setValue(element, text) else {
            Log.info("辅助功能写入失败，改用粘贴")
            return .unchanged
        }
        AX.select(element, location: (text as NSString).length, length: 0)
        return await waitForResult(element, before: before, expected: text, budget: 0.3)
    }

    // MARK: - Paste

    private static func paste(_ text: String, into element: AXUIElement, before: String) async -> InsertOutcome {
        AX.select(element, location: 0, length: (before as NSString).length)
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)
        let ours = stage(text, on: pasteboard)
        guard postCommand(CGKeyCode(kVK_ANSI_V)) else {
            restore(saved, on: pasteboard, ourChangeCount: ours)
            return .notApplied(leftOnClipboard: false)
        }
        // Generous budget: a busy app can take a while to handle ⌘V, and
        // restoring before it does would paste the old clipboard instead.
        let state = await waitForResult(element, before: before, expected: text, budget: 3)
        if state == .unchanged {
            return .notApplied(leftOnClipboard: pasteboard.changeCount == ours)
        }
        restore(saved, on: pasteboard, ourChangeCount: ours)
        return state == .done ? .inserted(.paste) : .mismatch
    }

    /// Pastes into an input box that cannot be read back (WeChat's), over
    /// what is in it when `replacing`. `landed` tells, by looking at the
    /// screen, whether the text arrived; until it does the clipboard keeps
    /// the suggestion, so a late paste still inserts the right text.
    static func pasteUnread(_ text: String, replacing: Bool, landed: () async -> Bool) async -> InsertOutcome {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)
        let ours = stage(text, on: pasteboard)
        guard (!replacing || postCommand(CGKeyCode(kVK_ANSI_A))), postCommand(CGKeyCode(kVK_ANSI_V)) else {
            restore(saved, on: pasteboard, ourChangeCount: ours)
            return .notApplied(leftOnClipboard: false)
        }
        let deadline = Date().addingTimeInterval(2.5)
        while Date() < deadline {
            try? await Task.sleep(nanoseconds: 150_000_000)
            if await landed() {
                restore(saved, on: pasteboard, ourChangeCount: ours)
                return .inserted(.paste)
            }
        }
        return .notApplied(leftOnClipboard: pasteboard.changeCount == ours)
    }

    nonisolated static func snapshot(_ pasteboard: NSPasteboard) -> ClipboardSnapshot {
        var concealed = false
        let items: [[NSPasteboard.PasteboardType: Data]] = (pasteboard.pasteboardItems ?? []).map { item in
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if type == concealedType { concealed = true }
                if let data = item.data(forType: type) { copy[type] = data }
            }
            return copy
        }
        return ClipboardSnapshot(items: items, concealed: concealed)
    }

    /// Puts the suggestion on the clipboard for this Mac only (no Universal
    /// Clipboard), marked so clipboard history tools skip it. Returns the
    /// change count that identifies this write.
    @discardableResult
    nonisolated static func stage(_ text: String, on pasteboard: NSPasteboard) -> Int {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Puts the earlier clipboard back, unless someone wrote to it since our
    /// write (their content wins). A concealed secret is cleared rather than
    /// rewritten: writing it again would look like a fresh copy to the password
    /// manager and stop it from clearing the secret later.
    @discardableResult
    nonisolated static func restore(_ saved: ClipboardSnapshot, on pasteboard: NSPasteboard, ourChangeCount: Int) -> Bool {
        guard pasteboard.changeCount == ourChangeCount else { return false }
        pasteboard.clearContents()
        guard !saved.concealed else { return true }
        let items: [NSPasteboardItem] = saved.items.map { copy in
            let item = NSPasteboardItem()
            for (type, data) in copy { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        return true
    }

    private static func postCommand(_ key: CGKeyCode) -> Bool {
        let source = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false) else { return false }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return true
    }
}
