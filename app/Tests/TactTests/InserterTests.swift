}

/// Runs against a private named pasteboard, never the user's clipboard.
@Suite(.serialized)
struct ClipboardTests {
    private func withPasteboard(_ body: (NSPasteboard) -> Void) {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("tact-test-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        body(pasteboard)
    }

    @Test func stagedTextIsMarkedForHistoryToolsToSkip() {
        withPasteboard { pb in
            Inserter.stage("建议", on: pb)
            let item = pb.pasteboardItems?.first
            #expect(item?.string(forType: .string) == "建议")
            #expect(item?.types.contains(Inserter.transientType) == true)
            #expect(item?.types.contains(Inserter.autoGeneratedType) == true)
        }
    }

    @Test func restorePutsTheOldContentBack() {
        withPasteboard { pb in
            pb.clearContents()
            pb.setString("原来复制的", forType: .string)
            let saved = Inserter.snapshot(pb)
            let ours = Inserter.stage("建议", on: pb)
            #expect(Inserter.restore(saved, on: pb, ourChangeCount: ours))
            #expect(pb.string(forType: .string) == "原来复制的")
        }
    }

    @Test func restoreKeepsWhatTheUserCopiedMeanwhile() {
        withPasteboard { pb in
            pb.clearContents()
            pb.setString("原来复制的", forType: .string)
            let saved = Inserter.snapshot(pb)
            let ours = Inserter.stage("建议", on: pb)
            pb.clearContents()
            pb.setString("刚复制的", forType: .string)
            #expect(!Inserter.restore(saved, on: pb, ourChangeCount: ours))
            #expect(pb.string(forType: .string) == "刚复制的")
        }
    }

    @Test func concealedSecretIsClearedNotRewritten() {
        withPasteboard { pb in
            let secret = NSPasteboardItem()
            secret.setString("hunter2", forType: .string)
            secret.setData(Data(), forType: Inserter.concealedType)
            pb.clearContents()
            pb.writeObjects([secret])
            let saved = Inserter.snapshot(pb)
            #expect(saved.concealed)
            let ours = Inserter.stage("建议", on: pb)
            #expect(Inserter.restore(saved, on: pb, ourChangeCount: ours))
            #expect(pb.string(forType: .string) == nil)
        }
    }

    @Test func emptyClipboardStaysEmpty() {
        withPasteboard { pb in
            pb.clearContents()
            let saved = Inserter.snapshot(pb)
            let ours = Inserter.stage("建议", on: pb)
            #expect(Inserter.restore(saved, on: pb, ourChangeCount: ours))
            #expect(pb.string(forType: .string) == nil)
        }
    }
}
