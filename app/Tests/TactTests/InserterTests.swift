import AppKit
import Testing
@testable import Tact

struct InsertPlanTests {
    @Test func autoTypesShortSingleLineText() {
        #expect(Inserter.plan("收到，我看一下", method: .auto, inputMethodActive: false) == [.type, .paste])
    }

    @Test func autoPastesWhileAnInputMethodIsActive() {
        #expect(Inserter.plan("收到，我看一下", method: .auto, inputMethodActive: true) == [.paste])
    }

    @Test func autoPastesLongOrMultilineText() {
        let long = String(repeating: "好", count: Inserter.maxTypedUTF16 + 1)
        #expect(Inserter.plan(long, method: .auto, inputMethodActive: false) == [.paste])
        #expect(Inserter.plan("第一行\n第二行", method: .auto, inputMethodActive: false) == [.paste])
    }

    @Test func typingLimitCountsUTF16Units() {
        // Each emoji is two UTF-16 units.
        let emoji = String(repeating: "👍", count: Inserter.maxTypedUTF16 / 2)
        #expect(Inserter.canType(emoji, inputMethodActive: false))
        #expect(!Inserter.canType(emoji + "👍", inputMethodActive: false))
        #expect(!Inserter.canType("", inputMethodActive: false))
    }

    @Test func explicitMethodsEndWithPaste() {
        #expect(Inserter.plan("好", method: .paste, inputMethodActive: false) == [.paste])
        #expect(Inserter.plan("好", method: .ax, inputMethodActive: false) == [.ax, .paste])
    }
}

